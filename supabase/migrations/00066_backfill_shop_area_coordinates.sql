-- マップ機能を動かすための、既存店舗のlat/lng一括投入(2026-09-12実施)。
--
-- 注意: これは実測値ではなく「エリア名 → そのエリアの中心座標」を割り当て、
-- 店舗IDのハッシュから作った決定的な擬似乱数で半径150m程度に散らしただけの
-- 暫定データ。同じビルの店舗が重なって1点に潰れるのを避けるのが目的で、
-- 実際の所在地とは一致しない。
-- 正確な位置にするには、店舗ごとに住所からジオコーディングして上書きする必要がある。
--
-- lat/lngが既に入っている店舗は対象外(where lat is null)なので、
-- 手動で正しい座標を入れた店舗を後から壊すことはない。
with area_centers(area, lat, lng) as (
  values
    ('横浜', 35.4437::double precision, 139.6380::double precision),
    ('すすきの', 43.0552, 141.3540),
    ('六本木', 35.6627, 139.7315),
    ('関内', 35.4460, 139.6390),
    ('銀座', 35.6717, 139.7650),
    ('歌舞伎町', 35.6938, 139.7034),
    ('池袋', 35.7295, 139.7109),
    ('那覇', 26.2124, 127.6809),
    ('渋谷', 35.6595, 139.7005),
    ('祇園', 35.0037, 135.7756),
    ('新横浜', 35.5079, 139.6172),
    ('梅田・京橋', 34.7024, 135.4959),
    ('北新地', 34.6970, 135.4959),
    ('中洲', 33.5945, 130.4066),
    ('秋葉原', 35.6984, 139.7731),
    ('上野', 35.7089, 139.7754),
    ('宮古島', 24.8057, 125.2810),
    ('ミナミ', 34.6687, 135.5013),
    ('下北沢', 35.6613, 139.6683),
    ('自由が丘', 35.6078, 139.6688),
    ('中野', 35.7076, 139.6638),
    ('中目黒', 35.6438, 139.6989),
    ('新宿', 35.6905, 139.7005),
    ('恵比寿', 35.6467, 139.7100),
    ('五反田', 35.6262, 139.7238),
    ('新橋', 35.6663, 139.7583)
),
jitter as (
  select
    s.id,
    ac.lat,
    ac.lng,
    (('x' || substr(md5(s.id::text || 'lat'), 1, 8))::bit(32)::bigint % 1000) / 1000.0 as rand_lat,
    (('x' || substr(md5(s.id::text || 'lng'), 1, 8))::bit(32)::bigint % 1000) / 1000.0 as rand_lng
  from public.shops s
  join area_centers ac on ac.area = s.area
  where s.status = 'active' and s.lat is null and s.lng is null
)
update public.shops s
set
  lat = j.lat + (j.rand_lat - 0.5) * 0.003,
  lng = j.lng + (j.rand_lng - 0.5) * 0.003
from jitter j
where j.id = s.id;
