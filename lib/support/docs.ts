/** locale は言語コード(公開サイトの4言語に加え、店舗向けは管理画面の言語。lib/i18n/languages.ts)。 */
export function docsFor(audiences: ("user" | "shop")[], locale: string = "ja"): SupportDoc[] {
  return SUPPORT_DOCS.filter((d) => audiences.includes(d.audience)).map((d) => localizeDoc(d, locale));
}

/**
 * 表示言語の機能カードにする。日本語が原本で、他言語は scripts/translate-support-docs.ts が
 * docs.i18n.json に作った翻訳。日本語が変わって翻訳が古いカード・翻訳が無いカードは、日本語のまま出す。
 */
function localizeDoc(doc: SupportDoc, locale: string): SupportDoc {
  if (locale === "ja") return doc;
  const stored = (TRANSLATIONS as unknown as Record<string, Record<string, string | { title?: string; body?: string }> | undefined>)[doc.id];
  const translated = stored?.[locale];
  if (!stored || !translated || typeof translated === "string" || stored.source_hash !== translationSourceHash({ title: doc.title, body: doc.body })) return doc;
  return { ...doc, title: translated.title ?? doc.title, body: translated.body ?? doc.body };
}
