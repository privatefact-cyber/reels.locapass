/**
 * サポートAIの質問の記録に残す前に、個人を特定できる情報(メールアドレス・電話番号)を伏せる。
 * AIには元の文章を渡すが、記録には伏せたものを残す(記録は、足りない機能カードを見つけるためで、個人情報は要らない)。
 */
export function maskPersonalInfo(text: string): string {
  return text
    .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, "[メール]")
    // 区切り(ハイフン・空白・括弧)が入っていてもよい、9桁以上の数字の並び(電話番号など)。
    .replace(/\+?\d[\d\s\-()]{7,}\d/g, "[電話番号]");
}
