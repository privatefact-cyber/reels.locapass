/** Vercelのリージョン値("13" / "JP-13" など)を2桁コードへ。判定不能なら空文字。 */
export function normalizePrefCode(raw: string | null | undefined): string {
  if (!raw) return "";
  const m = raw.match(/(\d{1,2})$/);
  if (!m) return "";
  const code = m[1].padStart(2, "0");
  return PREFECTURES[code] ? code : "";
}
